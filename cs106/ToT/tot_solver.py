# 3. Constraint Validator for Killer Sudoku
# ==========================================

def box_shape_for(grid_size: int) -> Tuple[str, int, int]:
    if grid_size == 9:
        return '3x3', 3, 3
    elif grid_size == 6:
        return '2x3', 2, 3
    else:
        raise ValueError(f"Unsupported grid size: {grid_size}")

def parse_cell(cell_str: str) -> Tuple[int, int]:
    """Parse cell string in format 'rXcY' to 0-indexed coordinates (row, col)."""
    parts = cell_str.lower().replace('r', '').split('c')
    row = int(parts[0]) - 1
    col = int(parts[1]) - 1
    return row, col

def check_constraints(board: List[List[int]], puzzle: Dict[str, Any]) -> bool:
    """
    Checks if the current board state is locally consistent.
    Returns True if valid (no violations), False if any constraint is violated.
    """
    grid_size = puzzle['grid_size']
    _, box_rows, box_cols = box_shape_for(grid_size)

    # 1. Row uniqueness
    for r in range(grid_size):
        row_vals = [board[r][c] for c in range(grid_size) if board[r][c] != 0]
        if len(row_vals) != len(set(row_vals)):
            return False

    # 2. Column uniqueness
    for c in range(grid_size):
        col_vals = [board[r][c] for r in range(grid_size) if board[r][c] != 0]
        if len(col_vals) != len(set(col_vals)):
            return False

    # 3. Box uniqueness
    for r_start in range(0, grid_size, box_rows):
        for c_start in range(0, grid_size, box_cols):
            box_vals = []
            for r in range(r_start, r_start + box_rows):
                for c in range(c_start, c_start + box_cols):
                    val = board[r][c]
                    if val != 0:
                        box_vals.append(val)
            if len(box_vals) != len(set(box_vals)):
                return False

    # 4. Killer cage sum and uniqueness
    for cage in puzzle['cages']:
        cells = cage['cells']
        target_sum = cage['sum']

        cage_vals = []
        empty_count = 0
        for r, c in cells:
            val = board[r][c]
            if val == 0:
                empty_count += 1
            else:
                cage_vals.append(val)

        # Cage uniqueness
        if len(cage_vals) != len(set(cage_vals)):
            return False

        current_sum = sum(cage_vals)
        # Cage sum constraints
        if empty_count == 0:
            if current_sum != target_sum:
                return False
        else:
            # Check if current sum already exceeds target
            if current_sum >= target_sum:
                return False
            # Check if minimum possible sum exceeds target
            # Each empty cell must be at least 1
            min_possible = current_sum + empty_count
            if min_possible > target_sum:
                return False
            # Check if maximum possible sum is less than target
            # Each empty cell can be at most grid_size
            max_possible = current_sum + empty_count * grid_size
            if max_possible < target_sum:
                return False

    return True

def validate_board_complete(board: List[List[int]], puzzle: Dict[str, Any]) -> Tuple[bool, str, List[str]]:
    """
    Validates a complete board against the ground truth solution and constraints.
    """
    grid_size = puzzle['grid_size']
    expected = list(range(1, grid_size + 1))
    _, box_rows, box_cols = box_shape_for(grid_size)
    errors = []

    if board is None:
        return False, 'No Prediction', ['prediction is None']
    if board == []:
        return False, 'Empty Prediction', ['model returned an empty board']
    if len(board) != grid_size or any(len(row) != grid_size for row in board):
        return False, 'Invalid Shape', [f'expected {grid_size}x{grid_size}, got {len(board)} rows']

    # Uniqueness checks
    for i, row in enumerate(board):
        if sorted(row) != expected:
            errors.append(f'Row {i + 1} invalid: {row}')

    for col in range(grid_size):
        column = [board[row][col] for row in range(grid_size)]
        if sorted(column) != expected:
            errors.append(f'Column {col + 1} invalid: {column}')

    for row_start in range(0, grid_size, box_rows):
        for col_start in range(0, grid_size, box_cols):
            nums = []
            for r in range(row_start, row_start + box_rows):
                for c in range(col_start, col_start + box_cols):
                    nums.append(board[r][c])
            if sorted(nums) != expected:
                errors.append(f'Subgrid ({row_start + 1},{col_start + 1}) invalid: {nums}')

    for idx, cage in enumerate(puzzle['cages']):
        values = [board[r][c] for r, c in cage['cells']]
        if sum(values) != cage['sum']:
            errors.append(f"Cage {idx + 1} sum invalid: got {sum(values)}, expected {cage['sum']}, values={values}")
        if len(values) != len(set(values)):
            errors.append(f'Cage {idx + 1} repeated digits: values={values}')

    if board != puzzle['solution']:
        errors.append('Prediction differs from provided solution')

    if errors:
        if any(err.startswith('Prediction differs') for err in errors) and len(errors) == 1:
            return False, 'Different From Solution', errors
        return False, 'Constraint Violation', errors

    return True, 'None', []


