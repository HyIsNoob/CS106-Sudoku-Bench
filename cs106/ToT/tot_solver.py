def grid_to_markdown(grid: List[List[int]]) -> str:
    rows = []
    rows.append('| ' + ' | '.join([''] * len(grid[0])) + ' |')
    rows.append('|' + '|'.join(['---'] * len(grid[0])) + '|')
    for row in grid:
        rows.append('| ' + ' | '.join(str(cell) for cell in row) + ' |')
    return '\n'.join(rows)

def get_empty_cells(board: List[List[int]]) -> List[str]:
    empty_cells = []
    for r in range(len(board)):
        for c in range(len(board[r])):
            if board[r][c] == 0:
                empty_cells.append(f"r{r+1}c{c+1}")
    return empty_cells

def build_cages_text(puzzle: Dict[str, Any]) -> List[str]:
    cages_text = []
    for cage in puzzle['cages']:
        cell_strs = [f'r{r+1}c{c+1}' for r, c in cage['cells']]
        cages_text.append('- ' + ' + '.join(cell_strs) + f" = {cage['sum']}")
    return cages_text


