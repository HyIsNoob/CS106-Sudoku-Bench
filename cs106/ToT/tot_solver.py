# ==========================================
# 1. Pydantic Models for LLM Responses
# ==========================================

class SudokuResult(BaseModel):
    board: List[List[int]] = Field(
        description="The solved Sudoku grid as a 2D list of integers."
    )

class SudokuAnalysisResult(BaseModel):
    analysis: str = Field(
        description="The logical analysis and scratchpad generated by the LLM, formatted according to the specified template."
    )

class SudokuFillResult(BaseModel):
    reasoning: str = Field(
        description="Briefly state why this digit is forced, or explain the logic behind your guess."
    )
    cell: str = Field(
        description="The cell being filled, in the format 'rXcY'. eg: 'r2c3' which means row 2 column 3 on the board."
    )
    value: int = Field(
        description="The digit being filled into the cell. Must be an integer from 1 to 9 (or 1 to 6)."
    )
    is_certain: bool = Field(
        description="True if this digit is mathematically forced, False if this is an educated guess based on candidate elimination."
    )


# ==========================================
# 2. Resilient API Call Wrapper with Retries
# ==========================================

def call_llm_with_retry(
    client: Any,
    model: str,
    contents: str,
    config: Any,
    max_retries: int = 5,
    initial_backoff: float = 5.0
) -> Any:
    """
    Calls Gemini API with exponential backoff on rate limits (429 / RESOURCE_EXHAUSTED).
    """
    backoff = initial_backoff
    for attempt in range(max_retries):
        try:
            response = client.models.generate_content(
                model=model,
                contents=contents,
                config=config
            )
            return response
        except Exception as e:
            err_msg = str(e)
            print(f"  [API Warning] Attempt {attempt+1} failed: {err_msg}")
            
            # Identify rate limit / quota exceeded errors
            is_rate_limit = (
                "429" in err_msg or 
                "RESOURCE_EXHAUSTED" in err_msg or 
                "quota" in err_msg.lower() or 
                "limit" in err_msg.lower()
            )
            
            if is_rate_limit and attempt < max_retries - 1:
                print(f"  [API Warning] Rate limit hit. Sleeping for {backoff:.1f}s before retry...")
                time.sleep(backoff)
                backoff *= 2.0  # Exponential backoff
            elif attempt < max_retries - 1:
                # Other transient errors
                print(f"  [API Warning] Transient error. Sleeping 2s before retry...")
                time.sleep(2.0)
            else:
                # Raise the exception if we run out of retries
                raise e


